package arreglo;

public class Arreglo {

    public static void main(String[] args) {
        int[] arr = {1, 2, 3, 4, 5, 6};

        System.out.println("---Ejercicio #1 de arreglo de 1 a 6---");

        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }
    }
}